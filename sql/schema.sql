-- FinGuard AI — Exasol Personal Columnar Schema
-- Track 01: Money, Risk & Regulation | ExaThon India 2026
-- Schema Version: 2.6.0

CREATE SCHEMA IF NOT EXISTS FINGUARD;
OPEN SCHEMA FINGUARD;

-- 1. CUSTOMERS TABLE
CREATE TABLE IF NOT EXISTS CUSTOMERS (
    CUSTOMER_ID VARCHAR(64) PRIMARY KEY,
    FULL_NAME VARCHAR(128) NOT NULL,
    EMAIL VARCHAR(128) NOT NULL,
    SEGMENT VARCHAR(32) NOT NULL, -- 'RETAIL', 'SME', 'CORPORATE', 'HNI'
    KYC_STATUS VARCHAR(32) NOT NULL, -- 'VERIFIED', 'TIER_1', 'PENDING_RECHECK'
    RISK_TIER VARCHAR(16) NOT NULL, -- 'LOW', 'MEDIUM', 'HIGH'
    ACCOUNT_CREATED_AT TIMESTAMP NOT NULL,
    MONTHLY_AVG_VOLUME DECIMAL(18,2) DEFAULT 0.00,
    AVG_TXN_AMOUNT DECIMAL(18,2) DEFAULT 0.00,
    STD_DEV_AMOUNT DECIMAL(18,2) DEFAULT 0.00,
    PRIMARY_COUNTRY VARCHAR(3) DEFAULT 'IND',
    DEVICE_COUNT INT DEFAULT 1,
    LAST_ACTIVITY_AT TIMESTAMP
);

-- 2. TRANSACTIONS TABLE
CREATE TABLE IF NOT EXISTS TRANSACTIONS (
    TXN_ID VARCHAR(64) PRIMARY KEY,
    CUSTOMER_ID VARCHAR(64) NOT NULL,
    TIMESTAMP TIMESTAMP NOT NULL,
    AMOUNT DECIMAL(18,2) NOT NULL,
    CURRENCY VARCHAR(8) DEFAULT 'INR',
    CHANNEL VARCHAR(32) NOT NULL, -- 'UPI', 'IMPS', 'NEFT', 'RTGS', 'SWIFT', 'CARD'
    COUNTERPARTY_ID VARCHAR(64) NOT NULL,
    COUNTERPARTY_NAME VARCHAR(128) NOT NULL,
    COUNTERPARTY_BANK VARCHAR(64) NOT NULL,
    COUNTERPARTY_COUNTRY VARCHAR(3) DEFAULT 'IND',
    IS_NEW_BENEFICIARY BOOLEAN DEFAULT FALSE,
    IP_ADDRESS VARCHAR(45),
    GEO_LAT DECIMAL(9,6),
    GEO_LON DECIMAL(9,6),
    DEVICE_ID VARCHAR(64),
    MERCHANT_CATEGORY VARCHAR(64) DEFAULT 'GENERAL_TRANSFER',
    DESCRIPTION VARCHAR(256),
    STATUS VARCHAR(32) DEFAULT 'FLAGGED', -- 'NORMAL', 'FLAGGED', 'UNDER_INVESTIGATION', 'CLEARED', 'REPORTED_SAR'
    CONSTRAINT FK_TXN_CUSTOMER FOREIGN KEY (CUSTOMER_ID) REFERENCES CUSTOMERS (CUSTOMER_ID)
);

-- 3. RISK_FEATURES TABLE (Calculated Analytical Vectors)
CREATE TABLE IF NOT EXISTS RISK_FEATURES (
    FEATURE_ID VARCHAR(64) PRIMARY KEY,
    TXN_ID VARCHAR(64) NOT NULL,
    CUSTOMER_ID VARCHAR(64) NOT NULL,
    CALC_TIMESTAMP TIMESTAMP NOT NULL,
    ROLLING_10M_COUNT INT DEFAULT 0,
    ROLLING_1H_COUNT INT DEFAULT 0,
    ROLLING_24H_COUNT INT DEFAULT 0,
    ROLLING_1H_VOLUME DECIMAL(18,2) DEFAULT 0.00,
    BASELINE_DEVIATION_RATIO DECIMAL(10,2) DEFAULT 1.00,
    IS_NEW_BENEFICIARY_FLAG BOOLEAN DEFAULT FALSE,
    OFF_HOURS_FLAG BOOLEAN DEFAULT FALSE,
    GEO_DISTANCE_KM DECIMAL(10,2) DEFAULT 0.00,
    DORMANT_DAYS INT DEFAULT 0,
    STRUCTURING_INDICATOR BOOLEAN DEFAULT FALSE,
    CONSTRAINT FK_FEAT_TXN FOREIGN KEY (TXN_ID) REFERENCES TRANSACTIONS (TXN_ID)
);

-- 4. RISK_ALERTS TABLE
CREATE TABLE IF NOT EXISTS RISK_ALERTS (
    ALERT_ID VARCHAR(64) PRIMARY KEY,
    TXN_ID VARCHAR(64) NOT NULL,
    CUSTOMER_ID VARCHAR(64) NOT NULL,
    ALERT_TIMESTAMP TIMESTAMP NOT NULL,
    FINAL_RISK_SCORE DECIMAL(5,2) NOT NULL, -- 0.00 to 100.00
    SEVERITY VARCHAR(16) NOT NULL, -- 'CRITICAL', 'HIGH', 'MEDIUM', 'LOW'
    TRIGGERED_RULES VARCHAR(512) NOT NULL, -- Comma-separated rule IDs
    RULE_CONTRIBUTIONS_JSON VARCHAR(4096),
    STATUS VARCHAR(32) DEFAULT 'NEW', -- 'NEW', 'REVIEWING', 'DISMISSED', 'ESCALATED'
    CASE_ID VARCHAR(64),
    CONSTRAINT FK_ALERT_TXN FOREIGN KEY (TXN_ID) REFERENCES TRANSACTIONS (TXN_ID)
);

-- 5. INVESTIGATION_CASES TABLE
CREATE TABLE IF NOT EXISTS INVESTIGATION_CASES (
    CASE_ID VARCHAR(64) PRIMARY KEY,
    TITLE VARCHAR(256) NOT NULL,
    PRIORITY VARCHAR(16) NOT NULL, -- 'P1_CRITICAL', 'P2_HIGH', 'P3_MEDIUM', 'P4_LOW'
    STATUS VARCHAR(32) NOT NULL, -- 'OPEN', 'IN_PROGRESS', 'PENDING_INFO', 'RESOLVED', 'CLOSED'
    ASSIGNED_ANALYST VARCHAR(128),
    CREATED_AT TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP NOT NULL,
    PRIMARY_TXN_ID VARCHAR(64) NOT NULL,
    RELATED_TXN_IDS_JSON VARCHAR(2048),
    DISPOSITION VARCHAR(64), -- 'CLEARED_FALSE_POSITIVE', 'SAR_FILED', 'ACCOUNT_FROZEN', 'ESCALATED_LEGAL'
    DISPOSITION_NOTES VARCHAR(4096),
    SAR_REFERENCE VARCHAR(64)
);

-- 6. AUDIT_EVENTS TABLE (Immutable Analyst Activity Trail)
CREATE TABLE IF NOT EXISTS AUDIT_EVENTS (
    EVENT_ID VARCHAR(64) PRIMARY KEY,
    EVENT_TIMESTAMP TIMESTAMP NOT NULL,
    ACTOR_ID VARCHAR(128) NOT NULL,
    ACTOR_ROLE VARCHAR(64) NOT NULL,
    ACTION_TYPE VARCHAR(64) NOT NULL, -- 'VIEW_TRANSACTION', 'COPILOT_QUERY', 'CREATE_CASE', 'UPDATE_DISPOSITION', 'MODIFY_RULE_CONFIG'
    TARGET_ENTITY VARCHAR(64) NOT NULL,
    TARGET_ID VARCHAR(64) NOT NULL,
    DETAILS_JSON VARCHAR(4096),
    PREV_STATE_HASH VARCHAR(64),
    CURR_STATE_HASH VARCHAR(64)
);

-- Indices for Fast Columnar Slice & Window Scans
CREATE INDEX IF NOT EXISTS IDX_TXN_TIME ON TRANSACTIONS (TIMESTAMP);
CREATE INDEX IF NOT EXISTS IDX_TXN_CUST ON TRANSACTIONS (CUSTOMER_ID);
CREATE INDEX IF NOT EXISTS IDX_ALERTS_SCORE ON RISK_ALERTS (FINAL_RISK_SCORE);
CREATE INDEX IF NOT EXISTS IDX_ALERTS_TIME ON RISK_ALERTS (ALERT_TIMESTAMP);
